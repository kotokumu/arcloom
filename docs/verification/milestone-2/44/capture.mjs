import fs from 'node:fs';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { finished } from 'node:stream/promises';

const [label, inputPath, wrapperName = 'codex-read-only.sh', binaryName = 'arcloom-plan'] = process.argv.slice(2);
if (!/^[a-z0-9-]+$/.test(label ?? '') || !inputPath) throw new Error('label and current evidence path required');
const root = '/private/tmp/arcloom-m2.7Hu4F2';
const directory = fs.mkdtempSync(path.join(root, label + '-'));
const fifo = path.join(directory, 'output.fifo');
if (spawnSync('mkfifo', ['-m', '600', fifo]).status !== 0) throw new Error('mkfifo failed');
const initialReader = fs.openSync(fifo, fs.constants.O_RDONLY | fs.constants.O_NONBLOCK);
const keeper = fs.openSync(fifo, fs.constants.O_WRONLY | fs.constants.O_NONBLOCK);
const reader = fs.openSync(fifo, fs.constants.O_RDONLY);
fs.closeSync(initialReader);
const output = fs.createReadStream('', { fd: reader, autoClose: true });
const chunks = [];
output.on('data', chunk => chunks.push(chunk));
const collected = finished(output);
const args = ['--owner', 'kotokumu', '--repo', 'arcloom', '--milestone', '2', '--codex', path.join(root, wrapperName), '--shutdown-grace', '5s', '--model', 'gpt-5.6-sol', '--effort', 'high', '--workdir', '/private/tmp/arcloom-assessment.H6WpvR', '--output-fifo', fifo, '--delivery-evidence', path.resolve(inputPath)];
const binary = path.join(root, binaryName);
const environment = { ...process.env };
const auth = spawnSync('gh', ['auth', 'token'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
if (auth.status !== 0 || !auth.stdout.trim()) throw new Error('GitHub credential unavailable');
environment.GITHUB_TOKEN = auth.stdout.trim();
delete environment.GH_TOKEN;
const startedAt = new Date().toISOString();
const child = spawn(binary, args, { env: environment, stdio: ['ignore', 'pipe', 'pipe'] });
console.log(JSON.stringify({ directory, pid: child.pid, startedAt }));
let stdoutBytes = 0;
let stderrBytes = 0;
child.stdout.on('data', data => { stdoutBytes += data.length; });
child.stderr.on('data', data => { stderrBytes += data.length; });
const cancel = () => child.kill('SIGTERM');
process.once('SIGINT', cancel);
process.once('SIGTERM', cancel);
const timeout = setTimeout(cancel, 180000);
const [exitCode, signal] = await new Promise((resolve, reject) => {
  child.once('error', reject);
  child.once('exit', (code, signal) => resolve([code, signal]));
});
clearTimeout(timeout);
fs.closeSync(keeper);
await collected;
const raw = Buffer.concat(chunks);
const hash = value => createHash('sha256').update(value).digest('hex');
const records = raw.toString('utf8').trim().split('\n').filter(Boolean).map(line => JSON.parse(line));
const manifest = { startedAt, completedAt: new Date().toISOString(), command: [binary, ...args], exitCode, signal, stdoutBytes, stderrBytes, binarySHA256: hash(fs.readFileSync(binary)), wrapperSHA256: hash(fs.readFileSync(path.join(root, wrapperName))), operatorInputSHA256: hash(fs.readFileSync(inputPath)), outputSHA256: hash(raw), records: records.length, githubAuthentication: 'existing gh credential in GitHub transport; removed from Codex environment by wrapper', codexAuthentication: 'existing ChatGPT login', observedCodexVersion: 'codex-cli 0.149.1', observedAppServerUserAgent: 'Codex Desktop/0.149.1 (Mac OS 26.5.2; arm64) dumb (arcloom-preflight; 1)', collector: 'owned FIFO reader; keeper descriptor writes no bytes and closes after command exit' };
fs.writeFileSync(path.join(directory, 'records.ndjson'), raw, { flag: 'wx', mode: 0o600 });
fs.writeFileSync(path.join(directory, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', { flag: 'wx', mode: 0o600 });
console.log(JSON.stringify({ ...manifest, command: undefined, directory, classifications: records.map(value => ({ type: value.type, classification: value.classification, outcome: value.assessment?.outcome, failure: value.failure, progress: value.progress?.tasks.map(task => ({ name: task.name, state: task.state })) })) }, null, 2));
process.exitCode = exitCode ?? 1;
